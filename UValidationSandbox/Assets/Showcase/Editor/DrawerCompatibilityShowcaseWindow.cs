using System;
using System.Linq;
using UnityEditor;
using UnityEditor.UIElements;
using UnityEngine;
using UnityEngine.UIElements;

namespace UValidation.Showcase.Editor
{
    /// <summary>
    /// Renders one showcase target through both supported property-drawer UI paths.
    /// </summary>
    internal sealed class DrawerCompatibilityShowcaseWindow : EditorWindow
    {
        private const float k_MinimumPaneWidth = 320.0f;

        [SerializeField] private UnityEngine.Object m_Target;

        private ObjectField m_TargetField;
        private VisualElement m_InspectorHost;
        private UnityEditor.Editor m_UiToolkitEditor;
        private UnityEditor.Editor m_ImguiEditor;

        /// <summary>
        /// Builds the comparison window.
        /// </summary>
        public void CreateGUI()
        {
            rootVisualElement.style.flexGrow = 1.0f;

            var toolbar = new Toolbar();
            m_TargetField = new ObjectField("Target")
            {
                allowSceneObjects = true,
                objectType = typeof(UnityEngine.Object)
            };
            m_TargetField.style.flexGrow = 1.0f;
            m_TargetField.RegisterValueChangedCallback(evt => SetTarget(evt.newValue));

            var useSelectionButton = new ToolbarButton(() => SetTarget(Selection.activeObject))
            {
                text = "Use Selection"
            };

            toolbar.Add(m_TargetField);
            toolbar.Add(useSelectionButton);
            rootVisualElement.Add(toolbar);

            m_InspectorHost = new VisualElement { style = { flexGrow = 1.0f } };
            rootVisualElement.Add(m_InspectorHost);

            SetTarget(m_Target != null ? m_Target : Selection.activeObject);
        }

        private void OnDisable()
        {
            ReleaseEditors();
        }

        [MenuItem("UValidation/Drawer Compatibility Showcase")]
        private static void OpenWindow()
        {
            var window = GetWindow<DrawerCompatibilityShowcaseWindow>();
            window.titleContent = new GUIContent("Drawer Compatibility");
            window.minSize = new Vector2(k_MinimumPaneWidth * 2.0f, 400.0f);
            window.Show();
        }

        private void SetTarget(UnityEngine.Object candidate)
        {
            m_Target = NormalizeTarget(candidate);
            m_TargetField?.SetValueWithoutNotify(m_Target);
            RebuildInspectors();
        }

        private void RebuildInspectors()
        {
            if (m_InspectorHost == null)
            {
                return;
            }

            ReleaseEditors();
            m_InspectorHost.Clear();

            if (m_Target == null)
            {
                m_InspectorHost.Add(new HelpBox(
                    "Select a showcase GameObject, component, or ScriptableObject, then click Use Selection.",
                    HelpBoxMessageType.Info));
                return;
            }

            m_UiToolkitEditor = UnityEditor.Editor.CreateEditor(m_Target);
            m_ImguiEditor = UnityEditor.Editor.CreateEditor(m_Target);
            if (m_UiToolkitEditor == null || m_ImguiEditor == null)
            {
                m_InspectorHost.Add(new HelpBox(
                    $"Unity could not create an Editor for '{m_Target.name}'.",
                    HelpBoxMessageType.Error));
                ReleaseEditors();
                return;
            }

            var splitView = new TwoPaneSplitView(
                0,
                Math.Max(k_MinimumPaneWidth, position.width * 0.5f),
                TwoPaneSplitViewOrientation.Horizontal);
            splitView.style.flexGrow = 1.0f;

            var uiToolkitScroll = AddPane(
                splitView,
                "UI Toolkit — CreatePropertyGUI",
                "Uses PropertyField controls generated by InspectorElement.FillDefaultInspector.");
            var uiToolkitInspector = new VisualElement();
            InspectorElement.FillDefaultInspector(
                uiToolkitInspector,
                m_UiToolkitEditor.serializedObject,
                m_UiToolkitEditor);
            uiToolkitInspector.Bind(m_UiToolkitEditor.serializedObject);
            uiToolkitScroll.Add(uiToolkitInspector);

            var imguiScroll = AddPane(
                splitView,
                "IMGUI — OnGUI / GetPropertyHeight",
                "Uses Unity's default IMGUI Editor inside an IMGUIContainer.");
            var imguiContainer = new IMGUIContainer(DrawImguiInspector)
            {
                style = { flexGrow = 1.0f }
            };
            imguiScroll.Add(imguiContainer);

            m_InspectorHost.Add(splitView);
        }

        private void DrawImguiInspector()
        {
            if (m_ImguiEditor == null || m_Target == null)
            {
                return;
            }

            m_ImguiEditor.serializedObject.UpdateIfRequiredOrScript();
            m_ImguiEditor.OnInspectorGUI();
        }

        private void ReleaseEditors()
        {
            if (m_UiToolkitEditor != null)
            {
                DestroyImmediate(m_UiToolkitEditor);
                m_UiToolkitEditor = null;
            }

            if (m_ImguiEditor != null)
            {
                DestroyImmediate(m_ImguiEditor);
                m_ImguiEditor = null;
            }
        }

        private static ScrollView AddPane(VisualElement splitView, string title, string description)
        {
            var pane = new VisualElement { style = { flexGrow = 1.0f } };
            pane.style.paddingLeft = 6.0f;
            pane.style.paddingRight = 6.0f;
            pane.style.paddingTop = 6.0f;
            pane.style.paddingBottom = 6.0f;

            var titleLabel = new Label(title);
            titleLabel.style.unityFontStyleAndWeight = FontStyle.Bold;
            titleLabel.style.fontSize = 13;
            titleLabel.style.marginBottom = 2.0f;
            pane.Add(titleLabel);

            var descriptionLabel = new Label(description);
            descriptionLabel.style.whiteSpace = WhiteSpace.Normal;
            descriptionLabel.style.marginBottom = 6.0f;
            pane.Add(descriptionLabel);

            var scrollView = new ScrollView(ScrollViewMode.Vertical)
            {
                style = { flexGrow = 1.0f }
            };
            pane.Add(scrollView);
            splitView.Add(pane);
            return scrollView;
        }

        private static UnityEngine.Object NormalizeTarget(UnityEngine.Object candidate)
        {
            if (candidate is GameObject gameObject)
            {
                return gameObject.GetComponents<MonoBehaviour>()
                    .FirstOrDefault(component => component != null && IsShowcaseType(component.GetType()));
            }

            return candidate is MonoBehaviour || candidate is ScriptableObject ? candidate : null;
        }

        private static bool IsShowcaseType(Type type)
        {
            return type.Namespace != null &&
                   type.Namespace.StartsWith("UValidation.Showcase", StringComparison.Ordinal);
        }
    }
}
